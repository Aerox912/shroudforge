bool verify_image(std::uintptr_t image,BCRYPT_ALG_HANDLE hash) noexcept {
    IMAGE_DOS_HEADER dos{};IMAGE_NT_HEADERS64 nt{};
    if(!safe_read(image,&dos,sizeof(dos))||dos.e_magic!=IMAGE_DOS_SIGNATURE||dos.e_lfanew<64||dos.e_lfanew>0x100000||
       image>UINTPTR_MAX-static_cast<std::uint32_t>(dos.e_lfanew)-sizeof(nt)||!safe_read(image+dos.e_lfanew,&nt,sizeof(nt))||
       nt.Signature!=IMAGE_NT_SIGNATURE||nt.FileHeader.Machine!=IMAGE_FILE_MACHINE_AMD64||
       nt.OptionalHeader.Magic!=IMAGE_NT_OPTIONAL_HDR64_MAGIC||nt.FileHeader.SizeOfOptionalHeader!=sizeof(IMAGE_OPTIONAL_HEADER64)||
       !nt.FileHeader.NumberOfSections||nt.FileHeader.NumberOfSections>96||nt.OptionalHeader.SizeOfImage>0x10000000||
       image>UINTPTR_MAX-nt.OptionalHeader.SizeOfImage)return false;
    std::array<IMAGE_SECTION_HEADER,96> sections{};
    const auto table=static_cast<std::size_t>(dos.e_lfanew)+sizeof(nt);
    const auto section_bytes=nt.FileHeader.NumberOfSections*sizeof(IMAGE_SECTION_HEADER);
    if(table>nt.OptionalHeader.SizeOfHeaders||section_bytes>nt.OptionalHeader.SizeOfHeaders-table||
       !safe_read(image+table,sections.data(),section_bytes))return false;
    std::array<unsigned char,8192> bytes{};
    for(const auto& guard:guards){
        if(guard.size>bytes.size()||guard.rva>nt.OptionalHeader.SizeOfImage||guard.size>nt.OptionalHeader.SizeOfImage-guard.rva)return false;
        bool found=false;
        for(unsigned i=0;i<nt.FileHeader.NumberOfSections;++i){
            const auto& section=sections[i];const auto size=(std::max)(section.Misc.VirtualSize,section.SizeOfRawData);
            if(section.VirtualAddress<=guard.rva&&guard.rva-section.VirtualAddress<size&&guard.size<=size-(guard.rva-section.VirtualAddress)&&
                section.Characteristics&IMAGE_SCN_MEM_EXECUTE){found=true;break;}
        }
        if(!found||!executable(image,image+guard.rva,guard.size)||!safe_read(image+guard.rva,bytes.data(),guard.size))return false;
        std::array<unsigned char,32> digest{};
        if(BCryptHash(hash,nullptr,0,bytes.data(),guard.size,digest.data(),static_cast<ULONG>(digest.size()))<0||digest!=guard.digest)return false;
    }
    return owned_world_call(image);
}

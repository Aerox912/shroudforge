bool executable(std::uintptr_t image,std::uintptr_t start,std::size_t bytes) noexcept {
    if(!start||bytes>UINTPTR_MAX-start)return false;
    const auto end=start+bytes;
    while(start<end){
        MEMORY_BASIC_INFORMATION region{};
        if(!VirtualQuery(reinterpret_cast<const void*>(start),&region,sizeof(region))||region.State!=MEM_COMMIT||
            reinterpret_cast<std::uintptr_t>(region.AllocationBase)!=image||region.Protect&(PAGE_GUARD|PAGE_NOACCESS))return false;
        const auto access=region.Protect&0xff;
        if(access!=PAGE_EXECUTE&&access!=PAGE_EXECUTE_READ&&access!=PAGE_EXECUTE_READWRITE&&access!=PAGE_EXECUTE_WRITECOPY)return false;
        const auto base=reinterpret_cast<std::uintptr_t>(region.BaseAddress);
        if(region.RegionSize>UINTPTR_MAX-base||base+region.RegionSize<=start)return false;
        start=(std::min)(end,base+region.RegionSize);
    }
    return true;
}

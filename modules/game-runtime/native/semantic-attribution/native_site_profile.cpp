bool rel32(std::uintptr_t target, std::uintptr_t next, std::int32_t& result) noexcept {
    if (target >= next) {
        const auto d=target-next;
        if(d>INT32_MAX) return false;
        result=static_cast<std::int32_t>(d);
    } else {
        const auto d=next-target;
        if(d>std::uint64_t(INT32_MAX)+1) return false;
        result=static_cast<std::int32_t>(-static_cast<std::int64_t>(d));
    }
    return true;
}

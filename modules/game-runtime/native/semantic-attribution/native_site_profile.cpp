bool RelocateOriginal(const Site& site, std::uintptr_t image,
                      std::uintptr_t pc, std::span<std::uint8_t> out,
                      std::size_t& written) noexcept {
    written=0;
    if(!site.instruction_count || site.instruction_count>site.instructions.size()) return false;
    for(std::size_t n=0;n<site.instruction_count;++n) {
        const auto& i=site.instructions[n];
        if(!i.size || i.size>i.bytes.size()) return false;
        std::array<std::uint8_t,20> b{};
        std::memcpy(b.data(),i.bytes.data(),i.size);
        std::size_t size=i.size;
        if(i.relocation==RelocationKind::OriginalStack) {
            if(i.modrm_offset>=i.size) return false;
            const auto d=std::int64_t(i.displacement)+8;
            if(d<INT32_MIN || d>INT32_MAX) return false;
            auto& modrm=b[i.modrm_offset];
            if((modrm&7)!=4 || (modrm&0xc0)==0xc0) return false;
            if(i.displacement_size==4) {
                if(i.displacement_offset+4>i.size) return false;
                const auto v=static_cast<std::int32_t>(d);
                std::memcpy(b.data()+i.displacement_offset,&v,4);
            } else {
                // No-displacement SIB and disp8 are the only other reviewed forms.
                const auto at=i.displacement_size?i.displacement_offset:i.modrm_offset+2;
                if((i.displacement_size!=0 && i.displacement_size!=1) || at>i.size) return false;
                const auto width=(d>=INT8_MIN && d<=INT8_MAX)?1U:4U;
                const auto old=i.displacement_size;
                if(at+old>i.size) return false;
                std::memmove(b.data()+at+width,b.data()+at+old,i.size-at-old);
                size+=width-old;
                modrm=(modrm&0x3f)|(width==1?0x40:0x80);
                if(width==1) b[at]=static_cast<std::uint8_t>(d);
                else {const auto v=static_cast<std::int32_t>(d);std::memcpy(b.data()+at,&v,4);}
            }
        } else if(i.relocation==RelocationKind::RipRelative) {
            if(i.displacement_size!=4 || i.displacement_offset+4>i.size) return false;
            std::int32_t d{};
            if(!rel32(image+i.rip_target_rva,pc+written+size,d)) return false;
            std::memcpy(b.data()+i.displacement_offset,&d,4);
        }
        if(written+size>out.size()) return false;
        std::memcpy(out.data()+written,b.data(),size);written+=size;
    }
    return true;
}
bool BuildRelay(const Site& site,std::uintptr_t image,std::uintptr_t base,
                std::uintptr_t common,RelayPlan& plan) noexcept {
    plan={};
    if(!image || !base || !common || site.expected_size<5) return false;
    std::size_t at{};
    auto call=[&](std::uint32_t& return_offset) {
        if(at+6>=RelayPlan::CommonPointerOffset) return false;
        plan.bytes[at]=0xff;plan.bytes[at+1]=0x15;
        const auto d=static_cast<std::int32_t>(RelayPlan::CommonPointerOffset-at-6);
        std::memcpy(plan.bytes.data()+at+2,&d,4);at+=6;
        return_offset=static_cast<std::uint32_t>(at);return true;
    };
    if(site.phase!=CapturePhase::After && !call(plan.before_return)) return false;
    std::size_t size{};
    if(!RelocateOriginal(site,image,base+at,
       std::span(plan.bytes).subspan(at,RelayPlan::CommonPointerOffset-at-7),size)) return false;
    at+=size;
    if(site.phase!=CapturePhase::Before && !call(plan.after_return)) return false;
    plan.bytes[at++]=0xc3;
    plan.code_size=static_cast<std::uint32_t>(at);
    std::memcpy(plan.bytes.data()+RelayPlan::CommonPointerOffset,&common,sizeof(common));
    // A leaf row: this relay's only stack adjustment is the original site CALL.
    plan.bytes[RelayPlan::UnwindOffset]=1;
    return true;
}
bool EncodeSiteCall(const Site& site,std::uintptr_t image,std::uintptr_t relay,
                    std::span<std::uint8_t> out) noexcept {
    if(site.expected_size<5 || out.size()!=site.expected_size) return false;
    std::int32_t d{};
    if(!rel32(relay,image+site.rva+5,d)) return false;
    std::memset(out.data(),0x90,out.size());out[0]=0xe8;
    std::memcpy(out.data()+1,&d,4);return true;
}
